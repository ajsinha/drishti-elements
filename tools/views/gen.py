"""drishti-views' specification: the pinned copy of the ViewModel schema and the compact form its validator reads.

    python3 tools/views/gen.py                     # write elements/drishti-views/src/drishti_views-schema.js from the copy
    python3 tools/views/gen.py --check             # exit 1 when the copy differs from its pin or the compact form is stale
    python3 tools/views/gen.py --sync ../drishti-rachana [--commit abc1234]
                                                   # copy spec/1/viewmodel.schema.json again, rewrite the pin, then write

The ViewModel specification has one home, drishti-rachana's ``spec/1/viewmodel.schema.json`` (decision N3). drishti-views ships a
byte-for-byte copy (``spec/drishti_viewmodel.schema.json``) whose SHA-256 is in ``spec/drishti_viewmodel.pin.json``. The compact form
is the copy without its annotations (``description``, ``title``, ``$comment``, ``$schema``, ``$id``, ``x-*``): only the keywords the
bundled validator implements. A schema that uses any other keyword is refused here, so the schema cannot outgrow its validator.
``tools/elements/build.py`` writes the same compact form (one build); this command is for the sync and for running it alone."""
from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import sys
from pathlib import Path

HOME = Path(__file__).resolve().parents[2]
VIEWS = HOME / "elements" / "drishti-views"
COPY = VIEWS / "spec" / "drishti_viewmodel.schema.json"
PIN = VIEWS / "spec" / "drishti_viewmodel.pin.json"
OUT = VIEWS / "src" / "drishti_views-schema.js"
SOURCE = Path("spec") / "1" / "viewmodel.schema.json"          # inside a drishti-rachana checkout

#: The keywords the validator (drishti_views-validate.js) implements; nothing else may appear in the compact form.
KEYWORDS = ("$ref", "$defs", "type", "properties", "required", "additionalProperties", "propertyNames", "items", "enum", "const",
            "pattern", "minimum", "maximum", "maxItems", "maxLength", "anyOf", "oneOf", "allOf", "if", "then", "format")
#: Annotations: read by people and tools, dropped from the compact form.
ANNOTATIONS = ("description", "title", "$comment", "$schema", "$id")
#: The names of a map (property names, definition names), not keywords.
MAPS = ("properties", "$defs")


class SpecError(Exception):
    """The copy or its schema cannot be used."""


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def compact(node, where: str = "#"):
    """The schema without annotations; a keyword the validator does not implement is refused with its place."""
    if isinstance(node, list):
        return [compact(x, f"{where}/{i}") for i, x in enumerate(node)]
    if not isinstance(node, dict):
        return node
    out = {}
    for k, v in node.items():
        if k in ANNOTATIONS or k.startswith("x-"):
            continue
        if k not in KEYWORDS:
            raise SpecError(f"{where}: the keyword {k!r} is not one the validator implements ({', '.join(KEYWORDS)})")
        if k in MAPS:
            out[k] = {name: compact(sub, f"{where}/{k}/{name}") for name, sub in v.items()}
        else:
            out[k] = compact(v, f"{where}/{k}")
    return out


def header() -> str:
    text = (HOME / "config" / "license-header.txt").read_text(encoding="utf-8").strip().splitlines()
    return "/*\n" + "".join(f" * {line}".rstrip() + "\n" for line in text) + " */\n"


def render() -> str:
    """The generated module: the compact schema, its contract and the hash of the copy it was made from."""
    pin = json.loads(PIN.read_text(encoding="utf-8"))
    raw = json.loads(COPY.read_text(encoding="utf-8"))
    body = json.dumps(compact(raw), separators=(",", ":"), ensure_ascii=False)
    contract = str(raw.get("x-contract") or pin["contract"])
    return (header()
            + "/* The ViewModel schema in its compact form. GENERATED by tools/elements/build.py (tools/views/gen.py) from\n"
            "   elements/drishti-views/spec/drishti_viewmodel.schema.json, the pinned copy of drishti-rachana's spec/1/viewmodel.schema.json:\n"
            "   do not edit (a static test refuses a stale copy). */\n\n"
            "/** The contract the schema describes, major.minor. @type {string} */\n"
            f"export const CONTRACT = {json.dumps(contract)};\n"
            "/** SHA-256 of the copy this form was made from (the pin). @type {string} */\n"
            f"export const SCHEMA_SHA256 = {json.dumps(pin['sha256'])};\n"
            "/** The compact schema (draft 2020-12 keywords only). @type {Object} */\n"
            f"export const SCHEMA = Object.freeze({body});\n")


def check_pin() -> list[str]:
    pin = json.loads(PIN.read_text(encoding="utf-8"))
    have = sha256(COPY)
    return [] if have == pin["sha256"] else [f"{COPY.relative_to(HOME)} has SHA-256 {have}, its pin says {pin['sha256']}: sync it (--sync)"]


def sync(rachana: Path, commit: str | None) -> None:
    src = rachana / SOURCE
    if not src.is_file():
        raise SpecError(f"{src}: no ViewModel schema there (a drishti-rachana checkout holds {SOURCE})")
    compact(json.loads(src.read_text(encoding="utf-8")))          # refused before anything is copied
    shutil.copyfile(src, COPY)
    pin = json.loads(PIN.read_text(encoding="utf-8"))
    pin["sha256"] = sha256(COPY)
    pin["contract"] = str(json.loads(COPY.read_text(encoding="utf-8")).get("x-contract") or pin["contract"])
    if commit:
        pin["commit"] = commit
    PIN.write_text(json.dumps(pin, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="exit 1 when the copy differs from its pin or the compact form is stale")
    ap.add_argument("--sync", metavar="DIR", help="a drishti-rachana checkout to copy spec/1/viewmodel.schema.json from")
    ap.add_argument("--commit", help="the drishti-rachana commit the copy is from (written into the pin)")
    a = ap.parse_args(argv)
    try:
        if a.sync:
            sync(Path(a.sync).resolve(), a.commit)
        problems = check_pin()
        text = render()
    except (SpecError, OSError, ValueError, KeyError) as e:
        print(f"views: {e}", file=sys.stderr)
        return 2
    if not OUT.is_file() or OUT.read_text(encoding="utf-8") != text:
        if a.check:
            problems.append(f"{OUT.relative_to(HOME)} is stale: run python3 tools/views/gen.py")
        else:
            OUT.write_text(text, encoding="utf-8")
            print(f"wrote: {OUT.relative_to(HOME)}")
    for p in problems:
        print(p, file=sys.stderr)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
